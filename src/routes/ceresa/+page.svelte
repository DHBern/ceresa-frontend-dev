	<h2 class="h2">Su Alice Ceresa...</h2>
	<p>
		Alice Ceresa (Basilea, 25 gennaio 1923 - Roma, 22 dicembre 2001) trascorre l’infanzia tra
		Basilea e Bellinzona, dove, per volontà paterna, compie studi commerciali e, per passione,
		inizia a scrivere, collaborando con il quotidiano «Il Dovere». Nei primi anni ‘40 si trasferisce
		a Zurigo, dove collabora con riviste e quotidiani come «Die Weltwoche» e «Svizzera italiana»,
		entrando in contatto con figure quali Franco Fortini e Ignazio Silone. In quegli stessi anni
		frequenta anche la scrittrice, pianista e psicoanalista junghiana Aline Valangin, che in quel
		periodo accoglie nella sua casa di Comologno, nel Canton Ticino, numerosi intellettuali esuli.
		Dopo soggiorni in Francia e nella Svizzera francese, grazie alla mediazione di Silone, nel 1950
		si stabilisce a Roma, dove pubblica su riviste come «Botteghe Oscure» e si avvicina agli
		ambienti dell’avanguardia italiana, mantenendo tuttavia una forte autonomia stilistica e
		concettuale. Parallelamente svolge un’intensa attività di traduttrice dal tedesco, spesso in
		collaborazione con l’editore Longanesi, traducendo in italiano opere di autori come Elias
		Canetti e Gerold Späth.
	</p>

	<p>
		Come narratrice esordisce nel 1943 con il racconto <em>Gli altri</em>, apparso sulla rivista
		«Svizzera italiana», e si afferma nel 1967 con il romanzo sperimentale
		<em>La figlia prodiga</em>
		(Einaudi), primo titolo della collana “La ricerca letteraria” e vincitore nello stesso anno del Premio
		Viareggio <em>Opera Prima</em>. Nel 1979 pubblica sulla rivista «Nuovi Argomenti» il racconto
		<em>La morte del padre</em>
		e nel 1990 il romanzo <em>Bambine</em> (Einaudi), vincitore del Premio Schiller, che affronta
		con sguardo lucido e corrosivo il tema dell’infanzia e della struttura patriarcale. A partire
		dagli anni Settanta lavora al
		<em>Piccolo dizionario dell’inuguaglianza femminile</em>, pubblicato postumo da nottetempo
		(2007, 2020).
	</p>

	<p>
		La sua opera, centrata sulla condizione femminile e sulla ricerca di forme linguistiche capaci
		di rappresentarla, coniuga rigore formale, ironia e tensione etica. Oggi Alice Ceresa è
		riconosciuta come una voce fondamentale della scrittura femminista e sperimentale del Novecento.
		Tradotti in francese e in tedesco, i suoi scritti principali conoscono negli ultimi anni nuove
		edizioni e un rinnovato interesse critico.
	</p>
</div>
