	<h2 class="h2">
		Edizione digitale degli inediti, dispersi, postumi. Gender, plurilinguismo, transnazionalità
	</h2>
	<p>
		Il progetto <em>Arcipelago Ceresa</em> mira a rendere accessibile, ricontestualizzare e
		valorizzare l’eredità letteraria della scrittrice italo-svizzera Alice Ceresa, la cui opera e
		attività intellettuale, pur al centro di un rinnovato interesse critico, restano in larga parte
		inesplorate. Proponendo un’edizione digitale delle opere inedite, disperse e postume, il
		progetto recupera e riunisce una parte significativa del corpus di testi ceresiani in un’unica
		piattaforma digitale ad accesso aperto (<em>Open Access</em>), che consentirà di sviluppare
		nuove prospettive di ricerca.
	</p>
	<p>
		Nel contesto di un corpus testuale eterogeneo (narrativa, saggistica, teatro e poesia), sarà
		fornita un’ampia selezione di scritti dispersi (che include la produzione giornalistica),
		inediti (saranno proposte parti significative di una trilogia di romanzi più volte annunciata ma
		mai completata) e postumi (tra cui il <em>Piccolo dizionario dell’inuguaglianza femminile</em>,
		in un’edizione ampliata e arricchita anche da materiali audio).
	</p>
	<p>
		La presenza di una componente multimediale riflette la peculiare configurazione dell’opera di
		Ceresa, la cui trasmissione non è rimasta circoscritta all’interno della cultura manoscritta e a
		stampa, ma si è estesa alla diffusione radiofonica. Saranno pertanto rese disponibili anche le
		letture radiofoniche di testi (in parte inediti) di Ceresa prodotte dalla Radio svizzera di
		lingua italiana alla fine degli anni Settanta.
	</p>
	<p>
		L’impegno editoriale sarà accompagnato da quattro progetti legati a due macroaree di ricerca:
		plurilinguismo e transnazionalità da un lato, <em>gender</em> e genere letterario dall’altro.
	</p>
	<p>
		Il gruppo di ricerca affiliato all’Università di Berna si focalizzerà sulla ricostruzione del
		profilo plurilingue dell’autrice, formatasi all’incrocio di lingue diverse (italiano, tedesco e
		francese), e sull’analisi dell’impatto esercitato da tale identità linguistica sulle sue
		pratiche creative. Saranno inoltre approfonditi i processi e le dinamiche transnazionali legate
		all’attività ceresiana, prestando in particolare attenzione al suo impegno nell’ambito della
		traduzione e al suo ruolo di mediatrice culturale.
	</p>
	<p>
		Il gruppo dell’Università di Zurigo, attraverso un approccio che si avvarrà delle prospettive
		filosofiche contemporanee sul genere, delle teorie decoloniali e dei <em>lesbian studies</em> degli
		anni Settanta, riprenderà e approfondirà le ricerche esistenti sullo sperimentalismo e sul femminismo
		nell’opera di Ceresa. Queste linee di ricerca saranno integrate con un’analisi della decostruzione
		dei generi letterari, intesa come liberazione dai vincoli della sessualità binaria e dalle forme di
		normatività di genere.
	</p>
</div>

<div class="mx-auto mt-25 flex w-full max-w-300 flex-col justify-center">
	<h2 id="cooperazioni" class="h2">Cooperazioni</h2>
	<h3 class="h3 mt-10">Data Science Lab (DSL), Berna</h3>
	<p>
		Il progetto dell’edizione digitale verrà realizzato in stretta collaborazione con il Data
		ScienceLab (DSL) dell’Università di Berna, e si avvarrà in particolare del supporto di Peter
		Dängeli e Levyn Bürki.
	</p>
	<p>
		Al DSL verranno affidati la gestione e conservazione del materiale digitalizzato tramite
		serverIIIF, lo sviluppo di prototipi, il supporto per le fasi di trascrizione e di codifica dei
		testi.Il DSL sarà inoltre responsabile della realizzazione delle componenti tecniche avanzate,
		tra cuila configurazione del workflow, l’implementazione del modello dati TEI e la
		trasformazioneautomatica dei testi OCR in formato TEI. Il laboratorio seguirà inoltre la
		finalizzazionedell’infrastruttura tecnica in vista del rilascio ufficiale dell’edizione
		digitale.
	</p>
	<p>
		Il DSL svolgerà anche un ruolo attivo nella progettazione dell’applicazione web, nello
		sviluppodelle interfacce interne ed esterne (front-end), nella gestione della distribuzione dei
		dati enella preparazione del lancio pubblico.
	</p>

	<h3 class="h3 mt-10">Archivio svizzero di letteratura (ASL), Berna</h3>
	<p>
		L’Archivio svizzero di letteratura (ASL) della Biblioteca nazionale svizzera, con sede a Berna,
		èpartner importante del progetto. Nel 2003 la Confederazione Svizzera ha infatti acquisito il <a
			href="https://ead.nb.admin.ch/html/ceresa.html">lascito di Alice Ceresa</a
		>, di cui detieneinteramente i diritti dal 2024. Per questo motivo, gran parte del corpus
		testuale che confluirànel progetto editoriale è stato selezionato dal patrimonio archivistico
		dell’ASL, che supportaattivamente le ricerche e fornisce le riproduzioni da includere
		nell’edizione digitale.
	</p>
</div>
